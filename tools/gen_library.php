<?php
/**
 * Embeds library/*.php into swm_library.h so the extension ships the
 * high level API (MongoClient, Db, Collection, ...) inside the .so.
 * Usage: php tools/gen_library.php
 */
$root = dirname(__DIR__);
$order = require $root . '/library/_order.php';
$out = "/* generated by tools/gen_library.php - do not edit */\n";
$out .= "typedef struct { const char *name; const char *code; size_t len; } swm_library_file;\n";
$out .= "static const swm_library_file swm_library[] = {\n";
foreach ($order as $file) {
    $code = file_get_contents("$root/library/$file");
    if ($code === false) { fwrite(STDERR, "missing $file\n"); exit(1); }
    $code = preg_replace('/^<\?php\s*/', '', $code);
    $code = preg_replace('/^declare\s*\(\s*strict_types\s*=\s*1\s*\)\s*;\s*/m', '', $code, 1);
    $lit = '';
    foreach (str_split($code, 2000) as $chunk) {
        $lit .= '    "' . addcslashes($chunk, "\0..\37\"\\?\177..\377") . "\"\n";
    }
    $out .= "  {\"@swoole-mongo/$file\",\n$lit    , " . strlen($code) . "},\n";
}
$out .= "};\n";
file_put_contents("$root/swm_library.h", $out);
echo "embedded " . count($order) . " files\n";
